-- كم صفاً سيتأثر؟ (شغّل هذا أولاً لتعرف)
select count(*) as عدد_طلاب_سابع_3
from class_roster
where cls = '7-3';

-- التحويل
update class_roster
set cls = '8-6'
where cls = '7-3';

-- تأكيد النتيجة
select cls as الصف, count(*) as عدد_الطلاب
from class_roster
group by cls
order by cls;
